def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, check=True, **kw)


# ---------------------------------------------------------------------------
# Executable provenance: bind each artifact to the binary that actually ran.
# ---------------------------------------------------------------------------


def binary_provenance(path) -> dict:
    """path/sha256/size/mtime of the executable an artifact measured.

    The git SHA in the fingerprint says what was checked out; this hash says
    what was built and executed. Fail closed: if the binary cannot be read,
    the runner refuses to produce evidence rather than recording a guess.
    """
    p = Path(path)
    h = hashlib.sha256()
    try:
        with open(p, "rb") as f:
            for block in iter(lambda: f.read(1 << 20), b""):
                h.update(block)
        st = p.stat()
    except OSError as e:
        sys.exit(f"cannot hash measured binary {p}: {e}")
    return {"path": str(p), "sha256": h.hexdigest(),
            "size": st.st_size, "mtime": st.st_mtime}


# ---------------------------------------------------------------------------
# Environment fingerprint. Optional metadata degrades to null/"unknown";
# the runner must never crash because one probe is unavailable. The build
# block is the exception: it comes from the actual xmake configuration
# (fail-closed), not from an assumption about how the tree was configured.
# ---------------------------------------------------------------------------


_TOOLCHAIN_CXX = {"clang": "clang++", "clangxx": "clang++",
                  "gcc": "g++", "gccxx": "g++"}


def _cxx_from_toolchain(toolchain: str | None) -> str | None:
    if toolchain in _TOOLCHAIN_CXX:
        return _TOOLCHAIN_CXX[toolchain]
    if toolchain:
        return toolchain + "++"
    return None


def xmake_config() -> dict:
    """The actual xmake configuration of this tree, via `xmake lua`.

    Runs a one-line probe against core.project.config in the repo, so
    build.mode/compiler describe the configuration that produced BENCH_BIN
    instead of a hardcoded "release"/"clang++". Missing xmake or an
    unconfigured tree is a hard error: evidence with an assumed build is
    worse than no evidence.
    """
    probe_dir = Path(tempfile.mkdtemp(prefix="sluice-xmake-probe-"))
    probe = probe_dir / "probe.lua"
    probe.write_text(
        'import("core.project.config")\n'
        'function main()\n'
        '    config.load()\n'
        '    local mode = config.get("mode")\n'
        '    local plat = config.get("plat")\n'
        '    local arch = config.get("arch")\n'
        '    local tc = config.get("toolchain")\n'
        '    if mode == nil or plat == nil or arch == nil then os.exit(9) end\n'
        '    print(string.format("%s|%s|%s|%s", mode, plat, arch, tc or ""))\n'
        'end\n'
    )
    try:
        out = subprocess.run(["xmake", "lua", str(probe)], cwd=REPO,
                             capture_output=True, text=True)
    except FileNotFoundError:
        sys.exit("xmake not found in PATH; cannot determine the real build "
                 "configuration for the artifact fingerprint")
    finally:
        shutil.rmtree(probe_dir, ignore_errors=True)
    if out.returncode != 0 or not out.stdout.strip():
        sys.exit("xmake config probe failed (is the tree configured? run "
                 "`xmake f -m release --toolchain=clang`): "
                 f"{out.stderr.strip()}")
    mode, plat, arch, tc = out.stdout.strip().splitlines()[-1].split("|")
    return {"mode": mode, "plat": plat, "arch": arch,
            "toolchain": tc or None}


def git_sha() -> dict:
    try:
        sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO,
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--short"], cwd=REPO,
                                    capture_output=True, text=True,
                                    check=True).stdout.strip())
        branch = subprocess.run(["git", "rev-parse", "--abbrev-ref", "HEAD"],
                                cwd=REPO, capture_output=True, text=True,
                                check=True).stdout.strip()
        return {"sha": sha, "dirty": dirty, "branch": branch}
    except (subprocess.CalledProcessError, FileNotFoundError):
        return {"sha": "unknown", "dirty": None, "branch": "unknown"}


def _first_line(cmd: list[str]) -> str | None:
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return out.stdout.splitlines()[0].strip() if out.stdout else None
    except (subprocess.CalledProcessError, FileNotFoundError, IndexError):
        return None


def detect_wsl() -> str:
    """Classify WSL2 | WSL1 | native | unknown from kernel release/version."""
    try:
        rel = Path("/proc/sys/kernel/osrelease").read_text().lower()
        ver = Path("/proc/version").read_text().lower()
        text = rel + " " + ver
        if "wsl2" in text or ("microsoft" in text and "-standard-" in rel):
            return "WSL2"
        if "microsoft" in text:
            return "WSL1"
        return "native"
    except OSError:
        return "unknown"


def parse_mountinfo(text: str, path: str) -> dict | None:
    """Longest-mount-point-prefix match for `path` in /proc/self/mountinfo.

    Returns {"mount_point":..., "type":...} or None. Field layout (see
    proc_pid_mountinfo(5)): fields 0..3 ids/root, field 4 mount point; after
    the " - " separator the first field is the filesystem type. Octal
    escapes (\\040 space, \\011 tab, \\012 newline, \\134 backslash) are
    decoded before matching.
    """
    best = None
    norm = os.path.normpath(path)
    for line in text.splitlines():
        if " - " not in line:
            continue
        left, right = line.split(" - ", 1)
        fields = left.split()
        if len(fields) < 5 or not right.split():
            continue
        mp = (fields[4].replace("\\040", " ").replace("\\011", "\t")
                      .replace("\\012", "\n").replace("\\134", "\\"))
        fstype = right.split()[0]
        if norm == mp or norm.startswith(mp.rstrip("/") + "/"):
            if best is None or len(mp) > len(best["mount_point"]):
                best = {"mount_point": mp, "type": fstype}
    return best


def mount_info(path: str | None) -> dict | None:
    """Mount record for `path` via /proc/self/mountinfo (preferred) or None."""
    if not path:
        return None
    try:
        text = Path("/proc/self/mountinfo").read_text()
        resolved = str(Path(path).resolve())
        found = parse_mountinfo(text, resolved)
        if found is None:
            return None
        return {"path": path, "mount_point": found["mount_point"],
                "type": found["type"]}
    except OSError:
        return None


def _cpu_model() -> str | None:
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return None


def _tool_version(cmd: list[str]) -> str | None:
    return _first_line(cmd + ["--version"])


def _glibc_ver() -> str | None:
    name, ver = platform.libc_ver()
    return f"{name} {ver}" if name and ver else None


def env_fingerprint(input_path: str | None = None,
                    output_path: str | None = None) -> dict:
    # Build metadata comes from the tree's actual xmake configuration (see
    # xmake_config); the compiler banner is probed from the derived
    # compiler so the full distribution context is recorded.
    cfg = xmake_config()
    cxx = _cxx_from_toolchain(cfg["toolchain"])
    if cxx is None:
        sys.exit(f"cannot derive the C++ compiler from toolchain "
                 f"{cfg['toolchain']!r}; refusing to guess build metadata")
    compiler_banner = _first_line([cxx, "--version"])
    if compiler_banner is None:
        sys.exit(f"cannot probe {cxx} --version for the build fingerprint")
    return {
        "time": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "git": git_sha(),
        "build": {
            "mode": cfg["mode"],
            "compiler": cxx,
            "compiler_version": compiler_banner,
            "plat": cfg["plat"],
            "arch": cfg["arch"],
            "toolchain": cfg["toolchain"],
        },
        "system": {
            "kernel": platform.release() or None,
            "platform": platform.machine() or None,
            "cpu": _cpu_model(),
            "logical_cpus": os.cpu_count(),
            "glibc": _glibc_ver(),
            "python": platform.python_version(),
        },
        "environment": {
            "wsl": detect_wsl(),
        },
        "filesystem": {
            # Where benchmark data files live (workload bytes in / out).
            "input": mount_info(input_path),
            # Where captured tool stdout goes (null when suppressed).
            "output": mount_info(output_path),
        },
        "tools": {
            "gnu_grep": _tool_version([GNU_GREP]),
            "ripgrep": _tool_version([RIPGREP]) if RIPGREP else None,
        },
    }


