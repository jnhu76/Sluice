#!/usr/bin/env python3
"""Sluice performance-attribution runner (docs/verification/
performance-attribution.md).

Reproducible, machine-readable benchmark driver for the attribution
campaign. Every command records the environment fingerprint (git SHA,
build, kernel, CPU, WSL state, filesystem mounts, tool versions) next to
the measurements so a result is always attributable to a build + machine +
workload, never hand-copied. Committed evidence artifacts are additionally
validated by scripts/bench/perf-evidence-validate.py.

Every artifact carries schema 2 and binds the exact executable it measured
(`binary`: path + sha256 + size + mtime) — the git SHA says what was
checked out, the binary hash says what actually ran, closing the
"checkout B but forgot to rebuild after A" hole.

Commands:
  ladder    Run grep_attribution_bench (L0..L4) over the workload matrix.
  cli       Run the L6 CLI matrix: sluice-grep vs GNU grep vs ripgrep on
            generated workload files (plus output byte-equality check).
  perf      Run one command under `perf stat`, capture hardware counters.
  compare   Side-by-side before/after table from two result JSON files,
            with environment-compatibility warnings.
  env       Print the environment fingerprint only.
  e1        #221 G0 / E1 abstraction-tax matrix: L0 raw pread/pwrite vs
            L1 minimal thread pool vs L2 Sluice ThreadPoolBackend, over
            the request-size x depth x workers sweep, per-cell process
            isolation, repetitions, provenance, and derived tax metrics
            (docs/verification/explicit-io-abstraction-tax.md).
  tax0      #250 TAX-0B/EXP-0 capacity-invariance matrix: fixed useful
            workload, one variable — unused request capacity C. Blocked
            randomized execution order from a predeclared seed, one bench
            process per measured repetition under user-mode perf stat,
            fail-closed same-work proof (research/tax0/).
  tax0u0    #250 TAX-0 EXP-U0 Uring router-scan causal ablation: the EXP-0
            geometry with ONE changed variable — router scan direction
            (production forward vs research reverse). Two arms x capacity
            list, blocked randomized (mode, C) order, per-row exact
            scan-iteration witness, preregistered baseline envelope and
            causal decision thresholds (research/tax0/).
  flame     Diagnostic CPU flame graph for one command: `perf record -g`
            -> `perf script` -> folded stacks -> self-contained SVG (no
            external FlameGraph checkout needed).
  e1bpf     Diagnostic eBPF counters for one command via bpftrace
            (pread64/pwrite64 entries, sched switches, migrations).
  self-test Hermetic unit tests for this runner's pure logic (no builds).

Competitor parity: GNU grep and ripgrep are invoked with `-a` (--text) so
binary workloads are processed with the same line-output semantics as
sluice-grep (which never special-cases binary data). Without it both tools
short-circuit on NUL detection ("Binary file matches") and their timings
measure a different output contract — not comparable evidence. All timed
commands run under LC_ALL=C so multibyte locales cannot change grep's
byte semantics.

Tool exit-code semantics (identical for sluice-grep, GNU grep, ripgrep):
0 = match found, 1 = no match (a legitimate benchmark outcome, NOT an
infrastructure failure), 2 = tool error (recorded as tool_error; the row
is invalid as performance evidence). The runner never treats a no-match
exit as a benchmark failure. `perf` records the child's exit status plus
an explicit exit_semantics classifier (grep-family: 0/1 are data;
strict-zero: only 0 is data) so the validator can enforce it.

Workload patterns are fetched from grep_workload_gen --print-pattern (the
generator's embedded matrix is the single source of truth; a duplicated
pattern table here could silently drift from the generated bytes).

Results are environment-sensitive; the JSON is the evidence, not a
universal performance claim.

Examples:
  perf-attribution.py ladder --bytes 268435456 --output out.json
  perf-attribution.py cli --bytes 1073741824 --output cli.json
  perf-attribution.py perf -- /path/to/sluice-grep pat file
  perf-attribution.py compare baseline.json optimized.json
"""
